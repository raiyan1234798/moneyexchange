// Stamps a unique id for THIS build. It is baked into the client bundle AND
// rendered into every page's HTML, so the app can tell "the server now serves a
// newer build than the code I'm running" with one exact comparison — instead of
// guessing from asset lists (which differ legitimately during SPA navigation).
import { mkdirSync, writeFileSync } from "node:fs";

const id = String(Date.now());
mkdirSync("src/lib", { recursive: true });
writeFileSync(
  "src/lib/build-id.ts",
  `// AUTO-GENERATED by scripts/gen-build-id.mjs at build time — do not edit.\nexport const BUILD_ID = "${id}";\n`,
);
console.log("build id:", id);
