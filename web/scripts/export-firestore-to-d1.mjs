/**
 * Export Firestore collections → JSON (+ optional D1 SQL) for Phase 2 migration.
 * Verifies row counts; never deletes Firestore data.
 *
 * Usage (from web/):
 *   BACKFILL_PASSWORD=... node scripts/export-firestore-to-d1.mjs
 *
 * Writes:
 *   scripts/out/firestore-export.json
 *   scripts/out/d1-seed.sql
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright-core";

const BASE = process.env.BACKFILL_BASE_URL || "https://unimoni-6va.pages.dev";
const EMAIL = process.env.BACKFILL_EMAIL || "admin@unimoni-signage.com";
const PASSWORD = process.env.BACKFILL_PASSWORD || "";
const PROJECT = process.env.FIREBASE_PROJECT_ID || "moneyexchange-35c33";

if (!PASSWORD) {
  console.error("Set BACKFILL_PASSWORD to export (admin account).");
  process.exit(1);
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, "out");
await mkdir(outDir, { recursive: true });

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await (await browser.newContext()).newPage();
await page.goto(`${BASE}/login/`, { waitUntil: "domcontentloaded" });
await page.getByRole("textbox", { name: /email/i }).fill(EMAIL);
await page.locator('input[type="password"]').first().fill(PASSWORD);
await page.getByRole("button", { name: /sign in/i }).click();
await page.waitForURL(/dashboard/, { timeout: 60000 });
await page.waitForTimeout(2000);

const token = await page.evaluate(async () => {
  const dbReq = indexedDB.open("firebaseLocalStorageDb");
  const idb = await new Promise((res, rej) => {
    dbReq.onsuccess = () => res(dbReq.result);
    dbReq.onerror = rej;
  });
  const rows = await new Promise((res, rej) => {
    const tx = idb.transaction("firebaseLocalStorage", "readonly");
    const rq = tx.objectStore("firebaseLocalStorage").getAll();
    rq.onsuccess = () => res(rq.result);
    rq.onerror = rej;
  });
  return rows.find((r) => r.fbase_key?.startsWith("firebase:authUser:")).value.stsTokenManager
    .accessToken;
});
await browser.close();

const FS = `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents`;
const H = { Authorization: `Bearer ${token}`, "Content-Type": "application/json" };

async function listCollection(collectionId, pageSize = 300) {
  const docs = [];
  let pageToken = "";
  do {
    const url = new URL(`${FS}/${collectionId}`);
    url.searchParams.set("pageSize", String(pageSize));
    if (pageToken) url.searchParams.set("pageToken", pageToken);
    const res = await fetch(url, { headers: H });
    const data = await res.json();
    if (data.error) throw new Error(JSON.stringify(data.error));
    for (const doc of data.documents || []) {
      docs.push(fromFirestoreDoc(doc));
    }
    pageToken = data.nextPageToken || "";
  } while (pageToken);
  return docs;
}

function fromFirestoreValue(v) {
  if (v == null) return null;
  if ("stringValue" in v) return v.stringValue;
  if ("integerValue" in v) return Number(v.integerValue);
  if ("doubleValue" in v) return v.doubleValue;
  if ("booleanValue" in v) return v.booleanValue;
  if ("nullValue" in v) return null;
  if ("timestampValue" in v) return v.timestampValue;
  if ("arrayValue" in v) return (v.arrayValue.values || []).map(fromFirestoreValue);
  if ("mapValue" in v) {
    const out = {};
    for (const [k, val] of Object.entries(v.mapValue.fields || {})) {
      out[k] = fromFirestoreValue(val);
    }
    return out;
  }
  return null;
}

function fromFirestoreDoc(doc) {
  const id = doc.name.split("/").pop();
  const data = {};
  for (const [k, v] of Object.entries(doc.fields || {})) {
    data[k] = fromFirestoreValue(v);
  }
  return { id, ...data };
}

function sqlEscape(s) {
  return String(s ?? "").replace(/'/g, "''");
}

console.log("Exporting Firestore collections…");
const collections = ["branches", "exchange_rates", "currencies"];
const exportPayload = { exportedAt: new Date().toISOString(), project: PROJECT, counts: {}, data: {} };

for (const name of collections) {
  const rows = await listCollection(name);
  exportPayload.data[name] = rows;
  exportPayload.counts[name] = rows.length;
  console.log(`  ${name}: ${rows.length}`);
}

const jsonPath = join(outDir, "firestore-export.json");
await writeFile(jsonPath, JSON.stringify(exportPayload, null, 2));
console.log("Wrote", jsonPath);

const sql = [];
sql.push("-- Generated by export-firestore-to-d1.mjs — review before wrangler d1 execute");
sql.push("BEGIN TRANSACTION;");

for (const b of exportPayload.data.branches) {
  const settings = JSON.stringify(b.settings ?? {});
  sql.push(
    `INSERT OR REPLACE INTO branches (id, code, name, status, logo_url, branding_color, settings_json, updated_at, firestore_synced_at) VALUES ('${sqlEscape(b.id)}', '${sqlEscape(b.code)}', '${sqlEscape(b.name)}', '${sqlEscape(b.status)}', '${sqlEscape(b.logoUrl)}', '${sqlEscape(b.brandingColor)}', '${sqlEscape(settings)}', '${sqlEscape(b.updatedAt)}', datetime('now'));`,
  );
  const note = b.settings?.rateCardNote ?? null;
  if (note != null && String(note).trim() !== "") {
    sql.push(
      `INSERT OR REPLACE INTO rate_card_notes (branch_id, note, updated_at, updated_by) VALUES ('${sqlEscape(b.id)}', '${sqlEscape(note)}', datetime('now'), 'export');`,
    );
  }
}

for (const r of exportPayload.data.exchange_rates) {
  sql.push(
    `INSERT OR REPLACE INTO exchange_rates (id, branch_id, currency_code, display_name, buy_rate, sell_rate, status, updated_at, payload_json) VALUES ('${sqlEscape(r.id)}', '${sqlEscape(r.branchId)}', '${sqlEscape(r.currencyCode)}', '${sqlEscape(r.displayName)}', ${Number(r.buyRate) || 0}, ${Number(r.sellRate) || 0}, '${sqlEscape(r.status)}', '${sqlEscape(r.updatedAt)}', '${sqlEscape(JSON.stringify(r))}');`,
  );
}

for (const c of exportPayload.data.currencies) {
  sql.push(
    `INSERT OR REPLACE INTO currencies (id, currency_code, payload_json, updated_at) VALUES ('${sqlEscape(c.id)}', '${sqlEscape(c.currencyCode)}', '${sqlEscape(JSON.stringify(c))}', '${sqlEscape(c.updatedAt)}');`,
  );
}

sql.push("COMMIT;");
const sqlPath = join(outDir, "d1-seed.sql");
await writeFile(sqlPath, sql.join("\n") + "\n");
console.log("Wrote", sqlPath);
console.log("Counts:", exportPayload.counts);
console.log("Next: wrangler d1 execute unimoni --remote --file=scripts/out/d1-seed.sql");
